CREATE TABLE IF NOT EXISTS pauta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    descricao VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS sessao_votacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inicio TIMESTAMP NOT NULL,
    fim TIMESTAMP,
    aberta BOOLEAN,
    id_pauta BIGINT NOT NULL,
    CONSTRAINT fk_sessao_pauta FOREIGN KEY (id_pauta) REFERENCES pauta(id)
);

CREATE TABLE IF NOT EXISTS voto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escolha VARCHAR(10),
    id_pauta BIGINT NOT NULL,
    id_sessao_votacao BIGINT NOT NULL,
    CONSTRAINT fk_voto_pauta FOREIGN KEY (id_pauta) REFERENCES pauta(id),
    CONSTRAINT fk_voto_sessao FOREIGN KEY (id_sessao_votacao) REFERENCES sessao_votacao(id)
);